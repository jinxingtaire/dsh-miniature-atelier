import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { assembleReferenceCases, templates } from '../src/reference-library.js'
import { stylePresets, styleLibraryNotes } from '../src/style-library.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const sceneFile = path.join(root, 'src', 'scenes.json')
const clientFile = path.join(root, 'src', 'client.js')
const cssFile = path.join(root, 'src', 'style.css')
const threeFile = path.join(root, 'src', 'three.min.js')
const sceneRuntimeFile = path.join(root, 'src', 'scene-runtime.js')
const outDir = path.join(root, 'lib')

const imageMap = {
  'ashen-cathedral': 'gothic.webp',
  'ink-mountain-temple': 'ink.webp',
  'brass-observatory': 'brass.webp',
  'cyber-rain-alley': 'cyber.webp',
  'desert-caravanserai': 'desert.webp',
  'polar-outpost': 'polar.webp',
}

const [scenesRaw, clientSource, css, threeSource, sceneRuntime, collectionRaw, lensRuntime] = await Promise.all([
  fs.readFile(sceneFile, 'utf8'),
  fs.readFile(clientFile, 'utf8'),
  fs.readFile(cssFile, 'utf8'),
  fs.readFile(threeFile, 'utf8'),
  fs.readFile(sceneRuntimeFile, 'utf8'),
  fs.readFile(path.join(root, 'src', 'sandbase-cases.json'), 'utf8'),
  fs.readFile(path.join(root, 'src', 'lens-runtime.js'), 'utf8'),
])
const scenes = JSON.parse(scenesRaw)
const collection = JSON.parse(collectionRaw)
const cases = assembleReferenceCases(collection.records)
for (const scene of scenes) {
  const file = imageMap[scene.id]
  if (!file) throw new Error(`No thumbnail mapping for ${scene.id}`)
  const bytes = await fs.readFile(path.join(root, 'assets', file))
  scene.image = `data:image/webp;base64,${bytes.toString('base64')}`
}

const covers = {}
for (const id of ['scene', 'machine', 'teardown', 'factory']) covers[id] = `data:image/webp;base64,${(await fs.readFile(path.join(root, 'assets', `cat-${id}.webp`))).toString('base64')}`

for (const token of ['__CATEGORY_COVERS__', '__SCENES__', '__REFERENCE_LIBRARY__', '__CSS__', '__THREE__', '__SCENE_RUNTIME__', '__LENS_RUNTIME__']) {
  if (!clientSource.includes(token)) throw new Error(`Missing build placeholder: ${token}`)
}

let code = clientSource
  .replace('__CATEGORY_COVERS__', () => JSON.stringify(covers))
  .replace('__SCENES__', JSON.stringify(scenes))
  .replace('__REFERENCE_LIBRARY__', () => JSON.stringify({ cases, templates, source: collection.source }))
  .replace('__CSS__', JSON.stringify(css))
  .replace('__THREE__', JSON.stringify(threeSource))
  .replace('__SCENE_RUNTIME__', JSON.stringify(sceneRuntime))
  .replace('__LENS_RUNTIME__', () => JSON.stringify(lensRuntime))
  .replaceAll('__STYLE_LIBRARY__', () => JSON.stringify({ styles: stylePresets, notes: styleLibraryNotes }))
if (code.includes('__SCENES__') || code.includes('__CSS__') || code.includes('__STYLE_LIBRARY__')) {
  throw new Error('A build placeholder was not replaced')
}

const bundle = `/**
 * Generated by scripts/build.mjs. Do not edit lib/client.js directly.
 * DSH client module loader wrapper; no external runtime imports.
 */
window.__ModuleLoader__.load({
  id: '@dsh-external/dsh-miniature-atelier',
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${code}
    exports.name = 'dsh-miniature-atelier';
    exports.inject = inject;
    exports.apply = apply;
    return module.exports;
  }
});
`

await fs.mkdir(outDir, { recursive: true })
await fs.writeFile(path.join(outDir, 'client.js'), bundle)
await fs.copyFile(path.join(root, 'src', 'index.js'), path.join(outDir, 'index.js'))
await fs.copyFile(path.join(root, 'src', 'reference-library.js'), path.join(outDir, 'reference-library.js'))
for (const file of ['full-scene.js', 'session-library.js', 'case-prompts.js', 'sandbase-cases.json', 'verify-full-scene.mjs', 'three.min.js', 'style-library.js', 'reference-images.js', 'creative-intent.js', 'modeling-parameters.js']) {
  await fs.copyFile(path.join(root, 'src', file), path.join(outDir, file))
}
console.log(`Built ${path.relative(process.cwd(), path.join(outDir, 'client.js'))} (${(bundle.length / 1024).toFixed(1)} KB)`)
